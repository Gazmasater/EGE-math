function solveFunctionImages(task){
 const d=defs[task.id];if(!d)return null;const v=d.v,answer=fmt(v.at(-1)),s=[];let check;
 if(d.family==='hyperbola'){
  const[x,y,t,a]=v,k=x*y;
  s.push(`Функция задана формулой f(x)=${F('k','x')}, где x≠0. Определим коэффициент по отмеченной на рисунке точке (${fmt(x)}; ${fmt(y)}). Её координаты удовлетворяют формуле функции.`,
  `Подставляем: ${fmt(y)}=${F('k',fmt(x))}, откуда k=${fmt(x)}·(${fmt(y)})=${fmt(k)}. Поэтому f(${t})=${F(fmt(k),t)}=${answer}.`,
  `Проверка: при x=${fmt(x)} полученная формула даёт ${F(fmt(k),fmt(x))}=${fmt(y)}, как на графике. Аргумент ${t} отличен от нуля, поэтому найденное значение определено.`);
  check=()=>{assert.equal(k/t,a);assert.equal(k/x,y);};
 }else if(d.family==='root'){
  const[a,t,r]=v;
  s.push(`Для функции f(x)=a√x область определения x≥0. На исходном графике отмечены точки (1; ${fmt(a)}) и (4; ${fmt(2*a)}). По первой точке получаем a√1=${fmt(a)}, то есть a=${fmt(a)}.`,
  `Проверяем коэффициент по второй точке: ${fmt(a)}√4=${fmt(a)}·2=${fmt(2*a)}. Обе отмеченные точки соответствуют формуле f(x)=${fmt(a)}√x.`,
  `Число ${t} принадлежит области определения. Следовательно, f(${t})=${fmt(a)}√${t}=${fmt(a)}·${Math.sqrt(t)}=${answer}. В ответ записываем значение функции, а не коэффициент перед корнем.`);
  check=()=>assert.equal(a*Math.sqrt(t),r);
 }else if(d.family==='exponential'){
  const[x,y,t,r]=v,a=x===1?y:1/y,base=x===1?fmt(y):F(1,y);
  s.push(`Для показательной функции f(x)=aˣ основание a положительно и не равно 1. По рисунку график проходит через точку (${fmt(x)}; ${y}), поэтому a^(${fmt(x)})=${y}.`,
  x===1?`Так как a¹=a, получаем a=${y}. Значит, f(x)=${y}ˣ и f(${fmt(t)})=${y}^(${fmt(t)})=${answer}.`:`По определению отрицательной степени a⁻¹=${F(1,'a')}. Из ${F(1,'a')}=${y} получаем a=${base}. Теперь f(${fmt(t)})=(${base})^(${fmt(t)})=${y}^(${-t})=${answer}.`,
  `Проверка: найденное основание даёт в отмеченной точке значение ${y}; при x=0 значение равно 1, что согласуется с пересечением оси Oy. Искомый аргумент ${fmt(t)} допустим, поскольку показательная функция определена для всех действительных x.`);
  check=()=>{assert.ok(Math.abs(a**t-r)<1e-8);assert.equal(a**x,y);};
 }else if(d.family==='log'){
  const[x,y,t,r]=v,a=y===1?x:1/x,base=y===1?fmt(x):F(1,x);
  s.push(`По графику логарифмической функции f(x)=logₐx читаем точку (${x}; ${fmt(y)}). Значит, logₐ${x}=${fmt(y)}, или по определению логарифма a^(${fmt(y)})=${x}.`,
  `Отсюда a=${base}. Условия a>0 и a≠1 выполнены. Искомый аргумент ${t}>0 также входит в область определения логарифма.`,
  `Представляем ${t} как степень основания: (${base})^(${fmt(r)})=${t}. Поэтому f(${t})=logₐ${t}=${answer}. Проверка обратным возведением в степень подтверждает и величину, и знак ответа; при основании меньше 1 значения на x>1 отрицательны.`);
  check=()=>{assert.ok(Math.abs(Math.log(t)/Math.log(a)-r)<1e-8);assert.ok(Math.abs(a**r-t)<1e-8);};
 }else if(d.family==='line'){
  const[b,t,r]=v,sg=b>0?'+1':'−1';
  s.push(`График прямой y=kx+b проходит через отмеченные точки (0; ${fmt(b)}) и (1; ${fmt(b+2)}). Из первой точки сразу следует b=${fmt(b)}.`,
  `Угловой коэффициент находим по приращениям координат: k=${F(`${fmt(b+2)}−(${fmt(b)})`,'1−0')}=2. Следовательно, f(x)=2x${sg}. Подстановка x=1 даёт ${fmt(b+2)}, как на исходном рисунке.`,
  `Теперь вычисляем значение вне изображённого участка: f(${t})=2·${t}${sg}=${answer}. Продлевать прямую на глаз не нужно: две точки полностью определили её уравнение.`);
  check=()=>assert.equal(2*t+b,r);
 }else if(d.family==='parabola'){
  const[r1,r2,t,r]=v,c=r1*r2;
  s.push(`На рисунке парабола пересекает ось Ox при x=${r1} и x=${r2}. Поэтому её формулу можно записать в виде f(x)=a(x−${r1})(x−${r2}). Отмеченная точка на оси Oy имеет координаты (0; ${c}).`,
  `Подставляем её: ${c}=a·(−${r1})·(−${r2})=${c}a, откуда a=1. Получаем f(x)=(x−${r1})(x−${r2}). Эта формула даёт оба нуля и нужное пересечение с Oy.`,
  `Вычисляем f(${fmt(t)})=(${fmt(t)}−${r1})(${fmt(t)}−${r2})=(${fmt(t-r1)})·(${fmt(t-r2)})=${answer}. Знак положителен: обе скобки отрицательны, а ветви параболы направлены вверх.`);
  check=()=>{assert.equal((t-r1)*(t-r2),r);assert.equal(r1*r2,c);};
 }else if(d.family==='two-lines'){
  const[b,r]=v;
  s.push(`Первая прямая проходит через точки (−${b}; 0) и (0; ${b}), поэтому её угловой коэффициент равен ${F(b,b)}=1, а свободный член равен ${b}. Её уравнение y=x+${b}.`,
  `Вторая прямая проходит через (0; 0) и (1; 2), значит, её уравнение y=2x. В точке пересечения значения y одинаковы: x+${b}=2x. Отсюда x=${b}.`,
  `Проверка: обе прямые при x=${b} имеют ординату y=${2*b}. Точка пересечения единственна, поскольку коэффициенты наклона 1 и 2 различаются. В ответ требуется абсцисса, то есть ${answer}.`);
  check=()=>assert.equal(r+b,2*r);
 }else if(d.family==='root-line'){
  const[a,n,r]=v,k=F(1,n);
  s.push(`По отмеченной точке (1; ${a}) на графике f(x)=a√x получаем a=${a}. Прямая g(x)=kx проходит через (0; 0) и (${n}; 1), поэтому k=${k}.`,
  `В точках пересечения ${a}√x=${k}x, причём x≥0. Умножаем на ${n} и выносим √x: √x(√x−${a*n})=0. Получаем x=0 или √x=${a*n}, то есть x=${r}.`,
  `Корень x=0 соответствует изображённой точке A в начале координат. Для точки B берём второй корень: x=${answer}. Проверка: f(${r})=${a}·${Math.sqrt(r)}=${a*Math.sqrt(r)}, g(${r})=${F(r,n)}=${r/n}; ординаты совпадают.`);
  check=()=>{assert.equal(a*Math.sqrt(r),r/n);assert.ok(r>0);};
 }else if(d.family==='parabola-line'){
  const[r0,k,r]=v;
  s.push(`Парабола проходит через начало координат и пересекает ось Ox ещё при x=${r0}, поэтому f(x)=a·x(x−${r0}). Её отмеченная точка (${r0+1}; ${r0+1}) даёт ${r0+1}=a·${r0+1}·1, откуда a=1.`,
  `Прямая g(x)=kx проходит через (1; ${k}), значит, k=${k}. Приравниваем значения: x(x−${r0})=${k}x, или x(x−${r0+k})=0. Корни: x=0 и x=${r}.`,
  `Первая точка пересечения A=(0; 0) уже видна на рисунке. Значит, абсцисса второй точки B равна ${answer}. Проверка: f(${r})=${r}·${r-r0}=${r*(r-r0)}, g(${r})=${k}·${r}=${k*r}; получены одинаковые значения.`);
  check=()=>assert.equal(r*(r-r0),k*r);
 }else if(d.family==='hyperbola-line'){
  const[x,y,b,r]=v,K=x*y,n=-x,h=b-y,m=(y-b)/x;
  s.push(`Общая точка A имеет по рисунку координаты (${fmt(x)}; ${fmt(y)}). Из f(x)=${F('K','x')} получаем K=${fmt(x)}·(${fmt(y)})=${K}. Прямая пересекает Oy в точке (0; ${fmt(b)}), поэтому её свободный член b=${fmt(b)}.`,
  `Её наклон m=${F(`${fmt(y)}−(${fmt(b)})`,fmt(x))}=${F(h,n)}. Уравнение пересечения: ${F(K,'x')}=${F(h,n)}x${fmt(b)}, x≠0. После умножения на ${n}x: ${h}x²${fmt(n*b)}x−${n*K}=0.`,
  `Это уравнение раскладывается в произведение ${h===1?'':h}(x+${n})(x−${r})=0. Корни x=−${n} и x=${r}. Отрицательный корень даёт уже известную A, а точке B соответствует x=${answer}.`,
  `Проверка второго корня в исходных формулах: f(${r})=${F(K,r)}=${fmt(K/r)}, g(${r})=${F(h,n)}·${r}${fmt(b)}=${fmt(m*r+b)}. Значения равны и x≠0.`);
  check=()=>{assert.ok(Math.abs(K/r-(m*r+b))<1e-9);assert.equal(-h*n*r,-n*K);assert.equal(h*(n-r),n*b);};
 }else if(d.family==='ultrasound'){
  const[f0,vv,r]=v;
  s.push(`Частоты измеряются в МГц, скорость — в метрах в секунду. Подставляем f₀=${f0}, v=${vv} и c=1500 в данную формулу v=c${F('f−f₀','f+f₀')}: ${vv}=1500${F(`f−${f0}`,`f+${f0}`)}. Частота f>0, поэтому знаменатель положителен.`,
  `Умножаем на f+${f0}: ${vv}(f+${f0})=1500(f−${f0}). Следовательно, ${1500-vv}f=${f0*(1500+vv)}, откуда f=${F(f0*(1500+vv),1500-vv)}=${r} МГц.`,
  `Проверка: 1500·${F(r-f0,r+f0)}=${vv} — заданная скорость погружения. Полученная частота больше испускаемой, что согласуется с положительной скоростью в данной формуле.`);
  check=()=>assert.equal(1500*(r-f0)/(r+f0),vv);
 }else if(d.family==='capacitor'){
  const[C,R,U,t,r]=v,coef=1.5*C*R,p=t/coef;
  s.push(`Используем формулу t=αRC·log₂(${F('U₀','U')}). Подставляем α=1,5, R=${R}·10⁶ Ом и C=${C}·10⁻⁶ Ф. Множители 10⁶ и 10⁻⁶ сокращаются, поэтому αRC=1,5·${R}·${C}=${fmt(coef)}.`,
  `При t=${t} с и U₀=${U} кВ получаем ${t}=${fmt(coef)}·log₂(${F(U,'U')}). Отсюда log₂(${F(U,'U')})=${p}, значит, ${F(U,'U')}=2^(${p})=${2**p}. Следовательно, U=${F(U,2**p)}=${r} кВ.`,
  `Проверка: напряжение положительно и меньше начального. Подстановка даёт ${fmt(coef)}·log₂(${F(U,r)})=${fmt(coef)}·${p}=${t} с. В ответе нужны киловольты, дополнительное умножение на тысячу не требуется.`);
  check=()=>assert.equal(coef*Math.log2(U/r),t);
 }else if(d.family==='bell'){
  const[nu,p1,alpha,T,A,r]=v,coef=nu*alpha*T;
  s.push(`В данной формуле A=ανT·log₂(${F('p₂','p₁')}) количество воздуха ν=5 моль указано на рисунке условия. Подставляем α=5,8, T=300 К: ανT=5,8·5·300=8700. Давления p₁ и p₂ выражаем в одинаковых единицах — атмосферах.`,
  `Получаем 26100=8700·log₂(${F('p₂',11)}), откуда log₂(${F('p₂',11)})=3. По определению логарифма ${F('p₂',11)}=2³=8, поэтому p₂=11·8=88 атм.`,
  `Проверка: 8700·log₂(${F(88,11)})=8700·3=26100 Дж. Давление выросло, что соответствует сжатию воздуха при опускании колокола. Искомое конечное давление равно 88 атм.`);
  check=()=>assert.equal(coef*Math.log2(r/p1),A);
 }
 s.push(`Ответ: ${answer}.`);return{id:task.id,answer,solution:s.join('\n\n'),diagram_svg:'',diagram_caption:'',family:d.family,check};
}
