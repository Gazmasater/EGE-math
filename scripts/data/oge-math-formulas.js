const models = [
  ['0A4D44', 'well', 6000, 4100, 20],
  ['041048', 'well', 6500, 4000, 11],
  ['86FCF3', 'well', 6000, 4100, 6],
  ['23D305', 'well', 6000, 4100, 4],
  ['FD331C', 'well', 6000, 4100, 9],
  ['7C8727', 'radius', 18, 6],
  ['6D0827', 'well', 6000, 4100, 5],
  ['FFD2DB', 'well', 6000, 4100, 10],
  ['6CC2D0', 'radius', 35, 5],
  ['A2285A', 'well', 6500, 4000, 14],
  ['696950', 'well', 6500, 4000, 13],
  ['B011A1', 'well', 6000, 4100, 7],
  ['518EE9', 'resistance', 150, 5],
  ['940661', 'well', 6500, 4000, 12],
  ['F54232', 'well', 6000, 4100, 8],
  ['FCB38D', 'resistance', 98, 7],
  ['D8F884', 'radius', 54, 10],
];
const number = value => String(value).replace('.', ',');
const records = models.map(([id, type, a, b, n]) => {
  const result = type === 'well' ? a + b * n : a / (b * b);
  const answer = number(result);
  let solution;
  if (type === 'well') {
    solution = `1. Определим значение переменной.
В формуле C = ${a} + ${b}n буква n обозначает количество колец. Для данного колодца n = ${n}. Стоимость C получается в рублях, поэтому перевод единиц не требуется.

2. Вычислим стоимость.
В выражении ${b}n подразумевается умножение. Сначала вычисляем произведение, затем прибавляем постоянную часть стоимости ${a} рублей:
${b} · ${n} = ${b * n}.
C = ${a} + ${b * n} = ${answer} рублей.
Постоянную часть ${a} прибавляем один раз: она не умножается на число колец.

3. Проверка.
Вычтем из полученной стоимости постоянную часть и разделим остаток на коэффициент при n:
⟦${answer} − ${a}¦${b}⟧ = ⟦${b * n}¦${b}⟧ = ${n}.
Получили исходное количество колец. Следовательно, вычисленная стоимость соответствует условию.

Ответ: ${answer}.`;
  } else if (type === 'radius') {
    solution = `1. Запишем данные и выразим радиус.
По условию a = ${a} м·с⁻², ω = ${b} с⁻¹. В формуле a = ω²R неизвестен радиус R. Поскольку ω ≠ 0, можно разделить обе части равенства на ω²:
R = ⟦a¦ω²⟧.

2. Подставим значения.
Все величины уже выражены в единицах, указанных в условии. Сначала возводим угловую скорость в квадрат:
ω² = ${b}² = ${b * b} с⁻².
R = ⟦${a} м·с⁻²¦${b * b} с⁻²⟧ = ⟦${a}¦${b * b}⟧ м = ${answer} м.
При делении единицы с⁻² сокращаются, поэтому радиус выражен в метрах. Полученная десятичная дробь точная, округлять её не нужно.

3. Проверка.
Подставим найденный радиус в исходную формулу:
ω²R = ${b * b} · ${answer} = ${a} м·с⁻².
Это заданное центростремительное ускорение. Радиус положителен, как и должно быть.

Ответ: ${answer}.`;
  } else {
    solution = `1. Выразим сопротивление.
Дано: P = ${a} Вт, I = ${b} А. Требуется найти R в омах. Используем заданную зависимость P = I²R. Так как I ≠ 0, делим обе части равенства на I²:
R = ⟦P¦I²⟧.

2. Выполним вычисления.
Мощность и сила тока уже заданы в нужных единицах. Сначала найдём квадрат силы тока:
I² = ${b}² = ${b * b} А².
Затем подставим данные в формулу сопротивления:
R = ⟦${a} Вт¦${b * b} А²⟧ = ⟦${a}¦${b * b}⟧ Ом = ${answer} Ом.
Делить мощность нужно на квадрат силы тока, а не на саму силу тока.

3. Проверка.
Рассчитаем мощность при найденном сопротивлении по исходной формуле:
P = I²R = ${b}² · ${answer} = ${b * b} · ${answer} = ${a} Вт.
Получена мощность из условия, значит, сопротивление найдено верно.

Ответ: ${answer}.`;
  }
  return { id, answer, solution, diagram_svg: '', diagram_caption: '' };
});
module.exports = { name: 'formulas', topic: '1.5', records,
  sources: require('./oge-math-formulas-sources.json') };
