const assert=require('node:assert/strict');
const {records}=require('./quantum-solutions');
const near=(a,b,eps=1e-10)=>assert.ok(Math.abs(a-b)<=eps*Math.max(Math.abs(b),1e-100),`${a} ≠ ${b}`);
function verifyPhysics(){
 const h=6.6e-34,c=3e8,e=1.6e-19,m=9.1e-31,checked=new Set();
 function check(id,test){assert.ok(records[id]);test(records[id]);checked.add(id);}
 const answer=(r,s)=>assert.equal(r.answer,s);
 check('002D3A',r=>{near(.1*4200*10,1e20*70*h*c/3.3e-7);answer(r,'100 г');});
 check('0EF025',r=>{near(2.376e-14*5/(h*6e14),3e5);answer(r,'≈ 2,4·10⁻¹⁴ Вт');});
 check('179F0F',r=>{const l=h/Math.sqrt(2*m*9.6e-25);near(l,4.993127144517619e-7);near((h/l)**2/(2*m),9.6e-25);answer(r,'≈ 5,0·10⁻⁷ м');});
 check('4EABE9',r=>{near(1e19*h*c/550e-9,60*.06);answer(r,'5,5·10⁻⁷ м = 550 нм');});
 for(const id of ['50F927','83BE32'])check(id,r=>{near(1100*.003/(h*c/600e-9),1e19);answer(r,id==='50F927'?'1,1 кВт':'3 мс');});
 check('5765F0',r=>{near(111.96636217394024/(4*Math.PI*6**2)*8e-6/(h*c/.6e-6),6e12);answer(r,'≈ 112 Вт');});
 check('B8794C',r=>{near(12500*1e20*h*c/3.3e-7,3.3e5+4200*100);answer(r,'1,25·10⁴ с');});
 check('968C16',r=>{near(2000*.001*1e-8,2*3/c);answer(r,'2,0·10³ Па');});
 check('2F6B86',r=>{near(2*.7*5e8*h*c/1.1e-10,1.26e-6);answer(r,'5·10⁸ м⁻³');});
 check('6D6EAB',r=>{near((16.32e-19/c)**2/(2*1.6795459704880817e-27),8.81e-27);answer(r,'≈ 1,68·10⁻²⁷ кг');});
 check('0B7954',r=>{const A=2.39*e,l=h*c/(2*A);near((h*c/(l/1.5)-A)/(h*c/l-A),2);answer(r,'≈ 2,59·10⁻⁷ м');});
 check('0BACBC',r=>{near((5.33e14-3.9975e14)/3.9975e14,1/3);answer(r,'≈ 4,0·10¹⁴ Гц');});
 check('2F5762',r=>{const A=2;near(2*A-A,2);near(3*A-A,4);answer(r,'4 эВ');});
 for(const[id,l,A,p,a]of [['4E30DA',200e-9,4.54*e,6.92641321320061e-25,'≈ 6,9·10⁻²⁵ кг·м·с⁻¹'],['CF6142',531e-9,1.73e-19,6.031451465415354e-25,'≈ 6,0·10⁻²⁵ кг·м·с⁻¹']])check(id,r=>{near(p*p/(2*m)+A,h*c/l);answer(r,a);});
 check('5BF1E9',r=>{const nu0=c/800e-9,nu=.75e15;near((2*nu-nu0)/(nu-nu0),3);answer(r,'8,0·10⁻⁷ м = 800 нм');});
 check('8185D1',r=>{const nu=c/250e-9;near((2*nu-6e14)/(nu-6e14),3);answer(r,'6·10¹⁴ Гц');});
 check('CEDDE6',r=>{const red=h*c/(h*c/300e-9-e*.9);near(red,3.8372093023255815e-7);near(h*c*(1/300e-9-1/red)/e,.9);answer(r,'≈ 3,84·10⁻⁷ м');});
 check('DD17C6',r=>{near(h*c/e*(1/200e-9-1/290e-9),1.920258620689655);assert.ok(r.answer.includes('анод отрицателен'));});
 check('19794E',r=>{near(h*6.69090909090909e14-1.89*e,e*100*.0087);answer(r,'≈ 6,7·10¹⁴ Гц');});
 check('3F1F2B',r=>{near(e*100*.0087375+1.89*e,h*6.7e14);answer(r,'≈ 8,7 мм');});
 check('3926A9',r=>{near(e*150*.0025+3.75*e,h*c/.3e-6);answer(r,'150 В·м⁻¹');});
 check('3E43EA',r=>{near(h*c/9.907926341072859e-8-3.74*e,e*100*.0875);answer(r,'≈ 9,9·10⁻⁸ м');});
 check('BD8A11',r=>{near(e*100*.00375+3.75*e,h*c/.3e-6);answer(r,'3,75 мм');});
 check('6F2B31',r=>{near(h*1.6e15-4.7*e+e*100*.2,21.9*e);answer(r,'1,6·10¹⁵ Гц');});
 check('95DAA2',r=>{near(h*c/200e-9-3.7*e+e*260*.05158653846153846,15.9*e);answer(r,'≈ 5,2 см');});
 check('3ECAE5',r=>{near((h*1e15-h*c/450e-9)/e*4000e-12,5.5e-9);answer(r,'1,0·10¹⁵ Гц');});
 check('5BD390',r=>{const A=2.4373626373626375e-19,p=Math.sqrt(2*m*(h*c/660e-9-A));near(p/(e*.001),.002);answer(r,'≈ 2,44·10⁻¹⁹ Дж');});
 check('D4025B',r=>{const nu=1.0106893106893109e15;near(Math.sqrt(2*m*(h*nu-4.42e-19))/(e*4e-4),.01);answer(r,'≈ 1,0·10¹⁵ Гц');});
 const crossed=(nu,A,E,B=.001)=>Math.sqrt(2*(h*nu-A)/m)*B-E;
 check('3CE1A2',r=>{near(crossed(6.2e14,2.39*e,0),242.69548595122004);assert.ok(crossed(6.2e14,2.39*e,300)<0);assert.ok(r.answer.startsWith('E >'));});
 check('45ECE8',r=>{const top=(2.39*e+m*(300/.001)**2/2)/h;near(top,6.41439393939394e14);assert.ok(crossed(6.2e14,2.39*e,300)<0);assert.ok(crossed(6.6e14,2.39*e,300)>0);assert.ok(r.solution.includes('ν > ⟦A¦h⟧'));});
 check('B387DC',r=>{near((h*6.2e14-m*(300/.001)**2/2)/e,2.3015625);assert.ok(crossed(6.2e14,2.39*e,300)<0);assert.ok(crossed(6.2e14,2.2*e,300)>0);assert.ok(r.answer.includes('< A <'));});
 check('F4B3A9',r=>{near(crossed(6.4e14,2.39*e,0),296.49972666444035);assert.ok(crossed(6.4e14,2.39*e,200)>0);assert.ok(crossed(6.4e14,2.39*e,300)<0);assert.ok(r.answer.startsWith('E <'));});
 check('0D14B6',r=>{near((1-1/4)/(1/4-1/9),5.4);answer(r,'5,4');});
 check('BF110A',r=>{near((1-1/4)/(1/4-0),3);answer(r,'3');});
 check('765857',r=>{near((1.4998399914657563e-24)**2/(2*m)+h*6e14,10.2*e);answer(r,'≈ 1,5·10⁻²⁴ кг·м·с⁻¹');});
 check('9C8F39',r=>{near(6.075*e+h*c/300e-9,10.2*e);answer(r,'≈ 6,1 эВ');});
 check('EB5C27',r=>{near((10.2*e-e*6.1)/h,9.93939393939394e14);answer(r,'≈ 1,0·10¹⁵ Гц');});
 check('FCD901',r=>{const nu=((2e-24)**2/(2*m)+3.4*e)/h;near(nu,4.154245754245754e15);near(-3.4*e+h*nu,(2e-24)**2/(2*m));answer(r,'≈ 4,15·10¹⁵ Гц');});
 check('A087CE',r=>{near(2000*.9993111764872206*2**(-(3+50/60)/15.3)/6000,.28);answer(r,'≈ 1,0 см³');});
 check('EBB156',r=>{near(14.64+14.64/4,18.3);near(Math.sqrt(14.64),Math.sqrt(4*3.66));answer(r,'14,64 МэВ');});
 for(const id of ['00B1EF','4DE913'])check(id,r=>{const P=1,n1=6e14,n2=7e14;assert.ok(P/(h*n2)<P/(h*n1));assert.ok(h*n2>h*n1);assert.ok(r.answer.includes('ток насыщения уменьшится'));assert.ok(r.solution.includes('недостаточно для точной формы'));});
 check('871B1A',r=>{assert.ok(h*c/250e-9>h*c/290e-9);assert.ok(h*c/400e-9<h*c/290e-9);assert.ok(r.answer.includes('аргоновой'));assert.ok(r.solution.includes('избыточные электроны'));});
 check('AC93C2',r=>{const aperture=.05,f1=.2,f2=.3,omega=f=>2*Math.PI*(1-f/Math.sqrt(f*f+aperture*aperture));assert.ok(omega(f2)<omega(f1));answer(r,'фототок насыщения уменьшится');});
 check('6C6442',r=>{near(.10065/(h*6.1e14)/20*e,.002);answer(r,'≈ 0,10 Вт');});
 check('83BB19',r=>{near(.21/(h*8.484848484848485e14)/30*e,.002);answer(r,'≈ 8,5·10¹⁴ Гц');});
 assert.deepEqual([...checked].sort(),Object.keys(records).sort());
 const old=require('./thermal-solutions').records.D6F721;
 near(1e5+.001/.210*(1-2**(-35/140))*8.31*318/50e-6,140042.2810456037);
 assert.equal(old.answer,'≈ 1,40·10⁵ Па');
 return{new:checked.size,previous:1};
}
module.exports={verifyPhysics};
