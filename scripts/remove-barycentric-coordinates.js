const select = db.prepare('SELECT solution FROM solutions WHERE task_id = ? AND published = 1');
const update = db.prepare('UPDATE solutions SET solution = ?, updated_at = ? WHERE task_id = ?');
db.exec('BEGIN');
try {
  for (const [taskId, before, after] of replacements) {
    const row = select.get(taskId);
    if (!row || !row.solution.includes(before)) throw new Error(`Не найден исходный фрагмент решения ${taskId}`);
    update.run(row.solution.replace(before, after), new Date().toISOString(), taskId);
  }
  db.exec('COMMIT');
  console.log(`Удалены барицентрические координаты: ${replacements.length}`);
} catch (error) {
  db.exec('ROLLBACK');
  throw error;
}
