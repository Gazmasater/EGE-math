const select = db.prepare('SELECT solution FROM solutions WHERE task_id = ? AND published = 1');
const update = db.prepare('UPDATE solutions SET solution = ?, updated_at = ? WHERE task_id = ? AND published = 1');
const now = new Date().toISOString();
db.exec('BEGIN');
try {
  for (const [taskId, previous, next] of replacements) {
    const row = select.get(taskId);
    if (!row || !row.solution.includes(previous)) throw new Error(`Не найден заменяемый фрагмент в решении ${taskId}`);
    update.run(row.solution.replace(previous, next), now, taskId);
  }
  db.exec('COMMIT');
  console.log(`Удалено векторных произведений: ${replacements.length}`);
} catch (error) {
  db.exec('ROLLBACK');
  throw error;
}
